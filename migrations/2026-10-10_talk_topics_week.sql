create or replace function private.talk_week(p_day date default null)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $f$
declare
  d date := coalesce(p_day, (now() at time zone 'Asia/Jerusalem')::date);
  r record;
  last_ord int;
  nxt public.talk_topics%rowtype;
  v_tr text;
  v_q text;
  nid text;
  made jsonb := '[]'::jsonb;
begin
  for r in select distinct t.dept from public.talk_topics t where t.active order by t.dept loop
    nid := 'w' || to_char(d, 'YYYYMMDD') || '-' || substr(md5(r.dept), 1, 6);
    continue when exists (select 1 from public.toolbox_talks k where k.id = nid);
    last_ord := null;
    select t.ord into last_ord from public.toolbox_talks k join public.talk_topics t on t.id = k.topic_id
      where k.dept = r.dept order by k.d desc nulls last, k.ts desc limit 1;
    select * into nxt from public.talk_topics t where t.dept = r.dept and t.active and t.ord > coalesce(last_ord, 0) order by t.ord limit 1;
    if not found then
      select * into nxt from public.talk_topics t where t.dept = r.dept and t.active order by t.ord limit 1;
    end if;
    v_tr := null; v_q := null;
    select k.trainer, k.trainer_qual into v_tr, v_q from public.toolbox_talks k
      where k.dept = r.dept and k.trainer is not null order by k.ts desc limit 1;
    insert into public.toolbox_talks (id, d, title, body, s, dept, quiz, topic_id, trainer, trainer_qual, created_by, ts)
      values (nid, d, 'הדרכה שבועית: ' || r.dept || ' - ' || nxt.title, nxt.body, 'טיוטה', r.dept, nxt.quiz, nxt.id, v_tr, v_q, 'routine', now());
    made := made || to_jsonb(nxt.id);
  end loop;
  insert into public.server_state(key, value, updated_at)
    values ('talk_week', jsonb_build_object('at', now(), 'day', d, 'made', made)::text, now())
    on conflict (key) do update set value = excluded.value, updated_at = excluded.updated_at;
  return made;
end
$f$;
