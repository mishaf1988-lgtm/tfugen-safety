#!/usr/bin/env python3
"""Build functions/_domains.js from project-files/domains/index.json (01/11/2026, Michael: the work split into
branches, for Claude and for the assistant). One list of words; the server copy is generated, never edited by hand.
Run after changing index.json:  python3 tools/domains-build.py   (domains-test.py fails when they differ)."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
esc = lambda s: ''.join('\\u%04x' % ord(c) if ord(c) > 127 else c for c in s)
def build():
    idx = json.load(open(os.path.join(ROOT, 'project-files/domains/index.json'), encoding='utf-8'))
    rows = []
    for k, v in idx.items():
        if k.startswith('_'): continue
        rows.append("  { key: '%s', file: '%s', name: '%s', words: [%s], forms: [%s] }," % (k, v['file'], esc(v['name']), ', '.join("'" + esc(w) + "'" for w in v['words']), ', '.join("'" + esc(f) + "'" for f in v.get('forms', []))))
    return ('// GENERATED by tools/domains-build.py from project-files/domains/index.json. Do not edit by hand.\n'
            '// The work branches (01/11/2026, Michael: "split all our work into branches ... for you and for the assistant").\n'
            '// A word of a branch in Michael\'s message = the assistant is told to read that branch\'s file first.\n'
            'export const DOMAINS = [\n' + '\n'.join(rows) + '\n];\n'
            '// Pure: the branches a text touches, in list order (a word is matched case-insensitively, anywhere).\n'
            '// 02/11/2026 (Michael: "do it: smart ranking and spelling mistakes"): a one-word branch word of 5 letters or more\n'
            '// also counts one letter away from a word of the text (tools/domain_match.py, the same rule for Claude).\n'
            'export function lev1(a, b) {\n'
            '  if (a === b) return true;\n'
            '  if (Math.abs(a.length - b.length) > 1) return false;\n'
            '  if (a.length > b.length) [a, b] = [b, a];\n'
            '  let i = 0;\n'
            '  while (i < a.length && a[i] === b[i]) i++;\n'
            '  return a.length === b.length ? a.slice(i + 1) === b.slice(i + 1) : a.slice(i) === b.slice(i + 1);\n'
            '}\n'
            'export function domainsOf(text) {\n'
            "  const t = String(text || '').toLowerCase();\n"
            "  const toks = [];\n"
            "  for (let w of (t.match(/[\\w\\u0590-\\u05ff.-]+/g) || [])) { w = w.replace(/^[.-]+|[.-]+$/g, ''); for (let i = 0; i < 3 && w.length >= 4; i++) { toks.push(w); if ('\\u05d5\\u05d4\\u05d1\\u05dc\\u05de\\u05e9\\u05db'.indexOf(w[0]) < 0) break; w = w.slice(1); } }\n"
            "  const hit = (w) => { w = w.toLowerCase(); return t.indexOf(w) >= 0 || (w.indexOf(' ') < 0 && w.length >= 5 && toks.some((x) => lev1(w, x))); };\n"
            '  return DOMAINS.filter((d) => d.words.some(hit));\n'
            '}\n'
            '// The line for the assistant\'s fire text; empty when no branch matches.\n'
            'export function domainLine(text) {\n'
            '  const ds = domainsOf(text);\n'
            "  return ds.length ? 'domain (read first, before any step: the checklist at the top of the branch file, then only the lines of the branch file and of its rules file that hold words of this message, grep -i; the whole file when you make a document or the lines do not answer): ' + ds.map((d) => d.file + ' + project-files/domains/rules/' + d.key + '.md').join(', ') : '';\n"
            '}\n'
            '// The controlled forms of every branch (paths under the desktop), checked weekly by routine-db forms_check.\n'
            'export const DOMAIN_FORMS = DOMAINS.flatMap((d) => d.forms.map((path) => ({ domain: d.key, path })));\n')
if __name__ == '__main__':
    open(os.path.join(ROOT, 'functions/_domains.js'), 'w', encoding='utf-8').write(build())
    print('functions/_domains.js written')
