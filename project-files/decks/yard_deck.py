def photo(s, x, y, w, h, f, credit):
    """Illustrative internet picture in a light frame, credit line at the frame bottom (img/yard/credits.json)."""
    D.rect(s, x, y, w, h, fill='F7F9FA', line=GREY, lw=0.75)
    D.pic(s, os.path.join(IMG, f), x + 0.06, y + 0.06, w - 0.12, h - 0.42)
    D.text(s, x, y + h - 0.34, w, 0.3, 'תמונה להמחשה: ' + credit, size=10, color=GREY, align='c')


def ask(s, y, q, h=0.72, x=0.6, w=W - 1.2, size=16):
    """One discussion line: the trainer asks the room."""
