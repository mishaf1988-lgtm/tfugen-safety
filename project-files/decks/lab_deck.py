def c(x):
    """A clause number such as 4(6) kept left-to-right inside the right-to-left footer."""
    return '\u202a' + x + '\u202c'


def photo(s, x, y, w, h, f, credit):
    """Illustrative internet picture in a light frame, credit line at the frame bottom (img/lab/credits.json)."""
